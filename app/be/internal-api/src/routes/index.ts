import { Router } from "express";
import { healthRouter } from "../modules/health/health.route";
import { authContext } from "../middlewares/auth-context.middleware";
import { internalServiceRoutes } from "./internal-service.routes";
import { adminContext } from "../middlewares/admin-context.middleware";
import { accountProvisioningRouter } from "../modules/accounts/account-provisioning.route";
import { accessLogsRouter } from "../modules/access-logs/access-logs.route";
import { auditTrailRouter } from "../modules/audit-trail/audit-trail.route";
import { industriesRouter } from "../modules/industries/industries.route";
import { accountsRouter } from "../modules/accounts/accounts.route";
import { picManagementRouter } from "../modules/pic/pic-management.route";
import { quotationsRouter } from "../modules/quotations/quotations.route";
import { studentManagementRouter } from "../modules/students/student-management.route";
import { courseCategoriesRouter } from "../modules/course-categories/course-categories.route";
import { roomsRouter } from "../modules/rooms/rooms.route";
import { trainersRouter } from "../modules/trainers/trainers.route";
import { coursesRouter } from "../modules/courses/courses.route";
import { requestFormsRouter, requestFormReviewRouter } from "../modules/request-forms/request-forms.route";
import { inAppNotificationsRouter } from "../modules/notifications/in-app-notifications.route";
export const routes = Router();
routes.use(healthRouter);
routes.use("/api/v1/internal", authContext);
routes.get("/api/v1/internal/me", (req, res) => res.json({ service: "internal-api", auth: req.auth }));
routes.use("/api/v1/internal/audit-trail", auditTrailRouter);
routes.use("/api/v1/internal/industries", industriesRouter);
routes.use("/api/v1/internal/accounts", accountsRouter);
routes.use("/api/v1/internal/pics", picManagementRouter);
routes.use("/api/v1/internal/quotations", quotationsRouter);
routes.use("/api/v1/internal/students", studentManagementRouter);
routes.use("/api/v1/internal/course-categories", courseCategoriesRouter);
routes.use("/api/v1/internal/rooms", roomsRouter);
routes.use("/api/v1/internal/trainers", trainersRouter);
routes.use("/api/v1/internal/courses", coursesRouter);
routes.use("/api/v1/internal/request-forms", requestFormsRouter);
routes.use("/api/v1/internal/request-form-review", requestFormReviewRouter);
routes.use("/api/v1/internal/notifications", inAppNotificationsRouter);
routes.use("/api/v1/internal-service", internalServiceRoutes);
routes.use("/api/v1/admin/accounts", adminContext, accountProvisioningRouter);
routes.use("/api/v1/admin/access-logs", adminContext, accessLogsRouter);
